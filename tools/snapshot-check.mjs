/*
 * Можно ли публиковать собранный срез расписания.
 *
 * Отдельный файл — чтобы это решение проверялось тестами без сети и без сайта
 * университета. Оно того стоит: 15.09.2026 вуз сменил вёрстку, парсер стал
 * находить ноль занятий, и сборщик пять дней подряд публиковал пустые срезы,
 * потому что «ноль» не считался ошибкой. Теперь считается.
 *
 * Тесты на страницах сайта такую беду не ловят по своей природе: они гоняются
 * на сохранённых копиях, а копии не меняются вместе с сайтом. Единственное
 * место, где смену вёрстки видно, — вот эта проверка живого ответа.
 */
'use strict';

/** Если пусто больше чем у стольких групп — это не расписание, а поломка. */
export const MAX_EMPTY_SHARE = 0.5;
/** Столько групп может не ответить по сетевым причинам. */
export const MAX_FAILED_SHARE = 0.2;

/**
 * @param {{groups: number, lessons: number, empty: number, failed: number,
 *          anchor: unknown}} stats итоги обхода
 * @returns {string|null} причина, по которой публиковать нельзя, или null
 */
export function verdict(stats) {
  const { groups = 0, lessons = 0, empty = 0, failed = 0, anchor = null } = stats || {};

  if (!groups) return 'список групп пуст — вёрстка сайта изменилась?';
  if (failed > groups * MAX_FAILED_SHARE)
    return `не ответили ${failed} групп из ${groups} — похоже на проблемы с сетью`;
  if (!lessons)
    return 'ни одного занятия на всём сайте — почти наверняка сменилась вёрстка';
  if (empty > groups * MAX_EMPTY_SHARE)
    return `у ${empty} групп из ${groups} расписание пустое — не публикуем такой срез`;
  if (!anchor)
    return 'на странице нет строки «Сегодня: … неделя» — чётность считать не от чего';
  return null;
}
